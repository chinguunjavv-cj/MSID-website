/**
 * Pre-generates responsive AVIF and WebP sizes of the photographic brand backgrounds.
 *
 *   npm run brand:variants
 *
 * Why: with Vercel's optimiser returning 402 the site serves image originals, so a phone
 * downloaded the full 1920px hero to fill a 375px screen — Lighthouse measured the hero as
 * the mobile LCP element at 8.3s. These are the sizes a `<picture>` element chooses between
 * instead, generated once here rather than per request by a service with an allowance.
 *
 * Each filename carries a hash of its source, so a variant never changes under a URL and
 * can be cached for a year (`next.config.ts` marks /brand/v/ immutable). Replace a source
 * photograph and rerun this: new hashes, new URLs, and the stale files for that source are
 * removed. The manifest it writes is what `BackdropImage` reads to know which sizes exist.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { basename, extname, join } from "node:path";
import sharp from "sharp";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const OUT_DIR = join(ROOT, "public", "brand", "v");
const MANIFEST = join(ROOT, "src", "lib", "brand-images.generated.ts");

/** The full-bleed backgrounds. Logos are small and flat, and gain nothing from this. */
const SOURCES = ["/brand/hero-bg.jpg", "/brand/steppe-altai.jpg"];

/** Phone, large phone / small tablet, laptop, desktop. Capped at the source's width. */
const WIDTHS = [640, 960, 1280, 1920];

mkdirSync(OUT_DIR, { recursive: true });
const manifest = {};

for (const src of SOURCES) {
  const file = join(ROOT, "public", src);
  const input = readFileSync(file);
  const hash = createHash("sha256").update(input).digest("hex").slice(0, 10);
  const name = basename(src, extname(src));
  const { width: sourceWidth } = await sharp(input).metadata();

  const widths = [...new Set(WIDTHS.map((w) => Math.min(w, sourceWidth)))].sort((a, b) => a - b);

  // Stale variants of this source (an older hash) go, so the folder never accumulates.
  for (const existing of readdirSync(OUT_DIR)) {
    if (existing.startsWith(`${name}.`) && !existing.startsWith(`${name}.${hash}.`)) {
      unlinkSync(join(OUT_DIR, existing));
    }
  }

  let bytes = 0;
  for (const w of widths) {
    const resized = sharp(input).resize({ width: w, withoutEnlargement: true });
    const avif = await resized.clone().avif({ quality: 50, effort: 4 }).toBuffer();
    const webp = await resized.clone().webp({ quality: 72 }).toBuffer();
    writeFileSync(join(OUT_DIR, `${name}.${hash}.${w}.avif`), avif);
    writeFileSync(join(OUT_DIR, `${name}.${hash}.${w}.webp`), webp);
    bytes += avif.length + webp.length;
    console.log(
      `  ${src}  ${String(w).padStart(4)}w  avif ${String(Math.round(avif.length / 1024)).padStart(4)} KB  webp ${String(Math.round(webp.length / 1024)).padStart(4)} KB`,
    );
  }
  console.log(`  ${src}: ${widths.length} sizes × 2 formats, ${Math.round(bytes / 1024)} KB total (original ${Math.round(input.length / 1024)} KB)\n`);

  manifest[src] = { name, hash, widths };
}

writeFileSync(
  MANIFEST,
  `// Generated by scripts/brand-variants.mjs — do not edit by hand. Rerun the script when a
// brand background photograph changes.

export type BrandVariant = { name: string; hash: string; widths: number[] };

export const BRAND_VARIANTS: Record<string, BrandVariant> = ${JSON.stringify(manifest, null, 2)};
`,
);
console.log(`manifest written: ${MANIFEST}`);
